/**
 * Genera supabase/schema.sql a partir del esquema SQLite real de NOVASTORE.
 *
 * Uso: node scripts/generate-supabase-schema.mjs
 * No toca la base: solo lee PRAGMA table_info / foreign_key_list / index_list.
 */
import Database from 'better-sqlite3';
import fs from 'node:fs';
import path from 'node:path';

const DB_PATH = process.env.DATABASE_PATH || path.join(process.cwd(), 'data', 'novastore.db');
const OUT = path.join(process.cwd(), 'supabase', 'schema.sql');

/** Orden padre → hijo para que las claves foráneas siempre existan. */
const ORDER = [
  'users',
  'categories',
  'products',
  'product_variants',
  'offers',
  'carts',
  'cart_items',
  'orders',
  'order_items',
  'payment_proofs',
  'balance_movements',
  'payment_methods',
  'settings',
  'login_attempts',
  'sessions',
  'recharge_requests',
  'support_threads',
  'support_messages',
];

const BLOB_COLUMNS = new Set(['payment_proofs.data', 'recharge_requests.data']);

const db = new Database(DB_PATH, { readonly: true });

const existing = db
  .prepare("SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'")
  .all()
  .map((row) => row.name);

const tables = [
  ...ORDER.filter((name) => existing.includes(name)),
  ...existing.filter((name) => !ORDER.includes(name)).sort(),
];

function quoteIdent(name) {
  return /^[a-z_][a-z0-9_]*$/i.test(name) ? name : `"${name.replace(/"/g, '""')}"`;
}

function pgType(table, column) {
  const type = String(column.type || '').toUpperCase();
  const key = `${table}.${column.name}`;
  if (BLOB_COLUMNS.has(key) || type.includes('BLOB')) return 'bytea';
  if (type.includes('INT')) {
    if (/^(is_|has_)/.test(column.name)) return 'smallint';
    return 'bigint';
  }
  if (type.includes('REAL') || type.includes('FLOA') || type.includes('DOUB')) return 'double precision';
  return 'text';
}

function literalDefault(value) {
  if (value === null || value === undefined) return null;
  const text = String(value);
  if (/^null$/i.test(text)) return null;
  if (/^-?\d+(\.\d+)?$/.test(text)) return text;
  if (/^'.*'$/.test(text)) return text;
  if (/^(true|false)$/i.test(text)) return text.toUpperCase();
  if (/^(CURRENT_TIMESTAMP|CURRENT_DATE|CURRENT_TIME)$/i.test(text)) return text.toUpperCase();
  return `'${text.replace(/'/g, "''")}'`;
}

const lines = [];
lines.push('-- NOVASTORE · esquema de la base de datos en Supabase (PostgreSQL)');
lines.push('-- Generado por scripts/generate-supabase-schema.mjs a partir del esquema SQLite.');
lines.push('-- Ejecutar una sola vez en Supabase → SQL Editor.');
lines.push('--');
lines.push('-- Notas de seguridad: la tienda habla con estas tablas solo desde el servidor');
lines.push('-- (clave anónima guardada en las variables de entorno del servidor, nunca en el');
lines.push('-- navegador) y todas las lecturas/escrituras se validan en las acciones del');
lines.push('-- servidor, que además limitan cada consulta al usuario autenticado.');
lines.push('');
lines.push('create extension if not exists pgcrypto;');
lines.push('');

for (const table of tables) {
  const columns = db.prepare(`PRAGMA table_info(${quoteIdent(table)})`).all();
  const foreignKeys = db.prepare(`PRAGMA foreign_key_list(${quoteIdent(table)})`).all();
  const integerPk = columns.find((column) => column.pk === 1 && String(column.type).toUpperCase().includes('INT'));
  const textPk = columns.find((column) => column.pk === 1 && !String(column.type).toUpperCase().includes('INT'));

  const defs = columns.map((column) => {
    let def = `  ${quoteIdent(column.name)} ${pgType(table, column)}`;
    if (integerPk && integerPk.name === column.name) {
      def += ' generated by default as identity primary key';
    } else if (textPk && textPk.name === column.name) {
      def += ' primary key';
    }
    if (column.notnull === 1 && !(column.pk === 1 && integerPk)) def += ' not null';
    const fallback = literalDefault(column.dflt_value);
    if (fallback !== null && column.pk !== 1) def += ` default ${fallback}`;
    return def;
  });

  for (const fk of foreignKeys) {
    const target = fk.table;
    if (!tables.includes(target)) continue;
    const onDelete = (fk.on_delete || 'NO ACTION').toUpperCase();
    defs.push(
      `  constraint ${quoteIdent(`${table}_${fk.from}_fkey`)} foreign key (${quoteIdent(fk.from)}) references public.${quoteIdent(target)}(${quoteIdent(fk.to)}) on delete ${onDelete}`,
    );
  }

  lines.push(`create table if not exists public.${quoteIdent(table)} (`);
  lines.push(defs.join(',\n'));
  lines.push(');');

  // Restricciones UNIQUE e índices declarados en SQLite.
  const indexes = db.prepare(`PRAGMA index_list(${quoteIdent(table)})`).all();
  for (const index of indexes) {
    const info = db.prepare(`PRAGMA index_info(${quoteIdent(index.name)})`).all();
    const cols = info.map((item) => quoteIdent(item.name)).filter(Boolean);
    if (cols.length === 0) continue;
    if (index.origin === 'u' && cols.length === 1) {
      lines.push(
        `alter table public.${quoteIdent(table)} add constraint ${quoteIdent(`${table}_${info[0].name}_key`)} unique (${cols.join(', ')});`,
      );
    } else if (index.origin === 'c') {
      lines.push(
        `create index if not exists ${quoteIdent(index.name)} on public.${quoteIdent(table)} (${cols.join(', ')});`,
      );
    }
  }
  lines.push('');
}

lines.push('-- Acceso para las claves de Supabase (la tienda usa la clave anónima solo en el servidor).');
for (const table of tables) {
  lines.push(`grant all on table public.${quoteIdent(table)} to anon, authenticated, service_role;`);
}
lines.push('grant usage, select on all sequences in schema public to anon, authenticated, service_role;');
lines.push('');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'));
console.log(`Esquema generado: ${OUT} (${tables.length} tablas)`);
for (const table of tables) {
  const count = db.prepare(`SELECT COUNT(*) AS c FROM ${quoteIdent(table)}`).get().c;
  console.log(`  ${table}: ${count} filas`);
}
