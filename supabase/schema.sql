-- servidor, que además limitan cada consulta al usuario autenticado.

create extension if not exists pgcrypto;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  password_hash text not null,
  phone text,
  role text not null default 'customer',
  balance_cents bigint not null default 0,
  is_active smallint not null default 1,
  created_at text not null,
  updated_at text not null default '',
  address text
);
alter table public.users add constraint users_email_key unique (email);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null,
  description text not null default '',
  image_url text,
  position bigint not null default 0,
  is_active smallint not null default 1,
  created_at text not null
);
alter table public.categories add constraint categories_slug_key unique (slug);
alter table public.categories add constraint categories_name_key unique (name);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  category_id bigint,
  name text not null,
  slug text not null,
  description text not null default '',
  image_url text,
  price_cents bigint not null,
  compare_price_cents bigint,
  stock bigint,
  is_active smallint not null default 1,
  is_featured smallint not null default 0,
  sold_count bigint not null default 0,
  created_at text not null,
  updated_at text not null,
  constraint products_category_id_fkey foreign key (category_id) references public.categories(id) on delete SET NULL
);
create index if not exists idx_products_category on public.products (category_id);
alter table public.products add constraint products_slug_key unique (slug);

create table if not exists public.product_variants (
  id bigint generated by default as identity primary key,
  product_id bigint not null,
  name text not null,
  price_cents bigint,
  stock bigint,
  position bigint not null default 0,
  is_active smallint not null default 1,
  constraint product_variants_product_id_fkey foreign key (product_id) references public.products(id) on delete CASCADE
);
create index if not exists idx_variants_product on public.product_variants (product_id);

create table if not exists public.offers (
  id bigint generated by default as identity primary key,
  title text not null,
  description text not null default '',
  product_id bigint,
  category_id bigint,
  discount_percent bigint not null,
  starts_at text,
  ends_at text,
  is_active smallint not null default 1,
  created_at text not null,
  constraint offers_category_id_fkey foreign key (category_id) references public.categories(id) on delete CASCADE,
  constraint offers_product_id_fkey foreign key (product_id) references public.products(id) on delete CASCADE
);

create table if not exists public.carts (
  id bigint generated by default as identity primary key,
  token text not null,
  user_id bigint,
  created_at text not null,
  updated_at text not null,
  constraint carts_user_id_fkey foreign key (user_id) references public.users(id) on delete CASCADE
);
