alter table public.carts add constraint carts_token_key unique (token);

create table if not exists public.cart_items (
  id bigint generated by default as identity primary key,
  cart_id bigint not null,
  product_id bigint not null,
  variant_id bigint,
  quantity bigint not null,
  created_at text not null,
  constraint cart_items_variant_id_fkey foreign key (variant_id) references public.product_variants(id) on delete CASCADE,
  constraint cart_items_product_id_fkey foreign key (product_id) references public.products(id) on delete CASCADE,
  constraint cart_items_cart_id_fkey foreign key (cart_id) references public.carts(id) on delete CASCADE
);
create index if not exists idx_cart_items_unique on public.cart_items (cart_id, product_id);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_number text not null,
  idempotency_key text,
  user_id bigint not null,
  status text not null default 'pendiente',
  payment_method text not null,
  payment_status text not null default 'pendiente',
  subtotal_cents bigint not null,
  discount_cents bigint not null default 0,
  total_cents bigint not null,
  contact_email text not null,
  contact_phone text,
  customer_note text,
  admin_note text,
  reviewed_by bigint,
  reviewed_at text,
  created_at text not null,
  updated_at text not null,
  constraint orders_reviewed_by_fkey foreign key (reviewed_by) references public.users(id) on delete NO ACTION,
  constraint orders_user_id_fkey foreign key (user_id) references public.users(id) on delete RESTRICT
